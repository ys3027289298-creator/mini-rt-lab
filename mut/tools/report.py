#!/usr/bin/env python3
"""Render results/results.json (+validate.json, sensitivity.json) into REPORT.md.

The report is the deliverable: capture-rate tables, the miss list, per-mutant
frame/diff image hashes, and copy-paste reproduce commands.

Stdlib only.
"""
import hashlib
import json
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.abspath(os.path.join(HERE, os.pardir))
RES = os.path.join(ROOT, "results")


def load(name):
    p = os.path.join(RES, name)
    if not os.path.exists(p):
        return None
    return json.load(open(p, encoding="utf-8"))


def pct(x):
    return "-" if x is None else "%.1f%%" % (100.0 * x)


def main():
    r = load("results.json")
    v = load("validate.json")
    s = load("sensitivity.json")
    if not r:
        sys.stderr.write("results/results.json missing; run tools/run_mutations.py\n")
        return 1

    cfg = r["config"]
    th = r["thresholds"]
    results = r["results"]
    summ = r["summary"]
    L = []
    A = L.append

    A("# bvh / material mutation test report")
    A("")
    A("Generated by `tools/report.py` from `results/results.json`.  Do not edit by hand.")
    A("")
    A("## 1. What this measures")
    A("")
    A("A defect is injected into `bvh/src/bvh.c` or `material/src/material.c`, the")
    A("patched source is compiled **unmodified** into a small path tracer")
    A("(`render/rt.c` calls the real module through `render/*_shim.c`, which")
    A("`#include` the module source), and the resulting frames are compared with")
    A("frames from the pristine sources.")
    A("")
    A("A defect counts as **caught** when at least one scene shows a visible change:")
    A("")
    A("- at least `%d` pixels differ by at least `%d` in some RGB channel (8-bit)." %
      (th["min_pixels"], th["vis_diff"]))
    A("")
    A("The comparison is **paired**: mutant and reference share camera, resolution,")
    A("sample count, seed, and RNG stream, so Monte-Carlo noise cancels.  That was")
    A("measured, not assumed -- see section 5.")
    A("")
    A("Neither the scene list nor the threshold was tuned per mutant.  Every mutant")
    A("is scored by the same rule on all scenes.")
    A("")
    A("Configuration: %dx%d, %d spp, seed %d, scenes: %s." %
      (cfg["w"], cfg["h"], cfg["spp"], cfg["seed"], ", ".join(cfg["scenes"])))
    A("Compiler: `%s`." % r.get("compiler", "unknown"))
    A("")

    A("## 2. Capture-rate summary")
    A("")
    A("| group | mutants | caught | capture rate |")
    A("|---|---:|---:|---:|")
    d = summ["defects"]
    A("| defects (visible by construction) | %d | %d | **%s** |" %
      (d["n"], d["caught"], pct(d["rate"])))
    ds = summ["defect_subthreshold"]
    A("| defect, below measured sensitivity floor | %d | %d | %s |" %
      (ds["n"], ds["caught"], pct(ds["rate"])))
    e = summ["equivalents"]
    A("| equivalent mutants (should survive) | %d | %d | %s (false positives) |" %
      (e["n"], e["caught"], pct(e["rate"])))
    A("")
    A("`as_expected` = **%d / %d**; violations: %s" %
      (summ["as_expected"], len(results),
       ", ".join("`%s`" % x for x in summ["wrong"]) or "none"))
    A("")

    A("### By module")
    A("")
    A("| module | defect mutants | caught | rate |")
    A("|---|---:|---:|---:|")
    for k, b in sorted(summ["by_module"].items()):
        A("| `%s` | %d | %d | %s |" % (k, b["n"], b["caught"],
                                       pct(b["caught"] / b["n"] if b["n"] else None)))
    A("")
    A("### By mutation operator")
    A("")
    A("| operator | defect mutants | caught | rate |")
    A("|---|---:|---:|---:|")
    for k, b in sorted(summ["by_operator"].items()):
        if not b["n"]:
            continue
        A("| `%s` | %d | %d | %s |" % (k, b["n"], b["caught"],
                                       pct(b["caught"] / b["n"])))
    A("")

    A("### Per-scene contribution")
    A("")
    A("A mutant is credited to a scene if that scene alone crosses the threshold.")
    A("")
    A("| scene | defects caught by this scene |")
    A("|---|---:|")
    for sc in cfg["scenes"]:
        n = 0
        for x in results:
            if x["kind"] in ("defect", "defect-subthreshold"):
                st = x["scenes"].get(sc)
                if st and st.get("status") == "ok" and \
                        st["max"] >= th["vis_diff"] and st["n_vis"] >= th["min_pixels"]:
                    n += 1
        A("| `%s` | %d |" % (sc, n))
    A("")
    A("### Detection margin")
    A("")
    A("For each defect, the number of visible pixels in its *best* scene,")
    A("against the %d-pixel threshold.  Small margins mean detection is close to" %
      th["min_pixels"])
    A("the noise floor; they are the mutants to re-check if the renderer changes.")
    A("")
    A("| mutant | best scene | visible px | max delta | margin |")
    A("|---|---|---:|---:|---:|")
    margin_rows = []
    for x in results:
        if x["kind"] not in ("defect", "defect-subthreshold"):
            continue
        per = [(sc, x["scenes"].get(sc)) for sc in cfg["scenes"]]
        per = [(sc, st) for sc, st in per if st and st.get("status") == "ok"]
        if not per:
            continue
        sc, st = max(per, key=lambda kv: kv[1]["n_vis"])
        margin_rows.append((x["id"], sc, st["n_vis"], st["max"]))
    for mid, sc, nv, md in sorted(margin_rows, key=lambda r: r[2]):
        A("| `%s` | `%s` | %d | %d | %.0fx |" %
          (mid, sc, nv, md, nv / th["min_pixels"]))
    A("")
    A("### Unit-test baseline")
    A("")
    A("Each mutant is also compiled as the module's own self-test, to show what the")
    A("existing `make test` would have caught.  This is context, not the criterion.")
    A("")
    A("| | modules | caught by self-test |")
    A("|---|---:|---:|")
    for kind in ("defect", "defect-subthreshold"):
        rows = [x for x in results if x["kind"] == kind]
        if not rows:
            continue
        n = sum(1 for x in rows if x["selftest"]["caught"])
        A("| %s | %d | %d |" % (kind, len(rows), n))
    A("")

    A("## 3. Miss list")
    A("")
    miss = [x for x in results if x["expected"] == "caught" and not x["caught"]]
    below = [x for x in results if x["kind"] == "defect-subthreshold"]
    if not miss and not below:
        A("No defect mutant survived the image oracle.")
    elif not miss:
        A("No defect expected to be visible survived.  One real defect is below")
        A("the measured sensitivity floor and is listed below.")
    else:
        for x in miss:
            A("### `%s` -- %s" % (x["id"], x["title"]))
            A("")
            A("- module: `%s`, operator: `%s`" % (x["module"], x["operator"]))
            A("- outcome: %s" % x["reason"])
            A("- unit self-test failing: %s" %
              (", ".join(x["selftest"]["failing"]) or "none"))
            A("")

    if below:
        A("")
        A("### Defects known to be under the visibility floor")
        A("")
        A("These are real defects whose photometric effect was measured to be too")
        A("small for 8-bit RGB to show.  They survive by construction; section 5")
        A("gives the measured floor.  They are listed separately so the headline")
        A("capture rate is not inflated or deflated by them.")
        A("")
        for x in below:
            A("- `%s` -- %s" % (x["id"], x["title"]))
            A("  - worst per-scene channel delta: %s" %
              ", ".join("%s %d" % (k, v.get("max", -1)) for k, v in x["scenes"].items()))
        A("")

    A("## 4. Evidence per mutant")
    A("")
    A("Paths are relative to `results/`.  `frame sha256` is over the raw RGB bytes")
    A("(header stripped); `diff sha256` is over the per-pixel maximum-channel delta")
    A("image, amplified x16 and clipped, which is a canonical, order-independent")
    A("digest of *where and how much* the frames differ.")
    A("")
    A("Reproduce any mutant:")
    A("")
    A("```sh")
    A("python3 -I tools/run_mutations.py --only <id> --out /tmp/one")
    A("python3 -I tools/raw2png.py /tmp/one/mutants/<id>/<scene>.raw out.png")
    A("python3 -I tools/raw2png.py /tmp/one/mutants/<id>/<scene>.raw diff.png /tmp/one/frames/<scene>.raw")
    A("```")
    A("")
    for x in results:
        verdict = "CAUGHT" if x["caught"] else "survived"
        A("### `%s` -- %s" % (x["id"], verdict))
        A("")
        A("- title: %s" % x["title"])
        A("- module / operator / kind: `%s` / `%s` / `%s`" %
          (x["module"], x["operator"], x["kind"]))
        A("- expected: %s, as expected: %s" % (x["expected"], x["as_expected"]))
        A("- unit self-test caught: %s%s" %
          (x["selftest"]["caught"],
           (" (failing: %s)" % ", ".join(x["selftest"]["failing"]))
           if x["selftest"]["failing"] else ""))
        if x.get("equivalence_note"):
            A("- equivalence: %s" % x["equivalence_note"])
        A("- mutated source sha256: `%s`" % (x.get("source_sha256") or "-"))
        A("")
        A("| scene | visible px | max delta | RMSE | frame sha256 | diff sha256 |")
        A("|---|---:|---:|---:|---|---|")
        for sc in cfg["scenes"]:
            st = x["scenes"].get(sc)
            if not st:
                A("| `%s` | - | - | - | not rendered | - |" % sc)
            elif st.get("status") != "ok":
                A("| `%s` | render error | - | - | `%s` | - |" %
                  (sc, st.get("detail", "")[:60].replace("|", "\\|")))
            else:
                A("| `%s` | %d | %d | %.2f | `%s` | `%s` |" %
                  (sc, st["n_vis"], st["max"], st["rmse"],
                   st["frame_sha256"][:16], st["diff_sha256"][:16]))
        A("")
        A("Artefacts: `%s/` (patched source, per-scene frames, `diff_<scene>.png`)." %
          (x.get("sandbox") or "mutants/%s" % x["id"]))
        A("")

    A("## 5. Oracle validation")
    A("")
    if not v:
        A("`results/validate.json` missing -- run `tools/validate.py`.")
    else:
        ok = v["pass"]
        A("`tools/validate.py` result: **%s**." % ("PASS" if ok else "FAIL"))
        A("")
        A("| check | result |")
        A("|---|---|")
        A("| same binary, same inputs -> byte-identical frames | %s |" %
          all(c["identical"] for c in v["checks"]["determinism"].values()))
        A("| two independent builds -> identical frames | %s |" %
          all(c["identical"] for c in v["checks"]["build_stability"].values()))
        A("| BVH traversal == unaccelerated all-boxes path | %s |" %
          all(c["tree_equals_brute"] for c in v["checks"]["tree_equals_brute"].values()))
        A("| paired noise floor (same seed, pristine twice) is zero | %s |" %
          all(c["n_vis"] == 0 for c in v["checks"]["paired_noise_floor"].values()))
        A("")
        A("Unpaired frames (a different seed) differ in most pixels, by up to")
        A("`%d` levels in some channel:" % max(c["max"] for c in
                                              v["checks"]["unpaired_noise_floor_seed_diff"].values()))
        A("")
        A("| scene | differing px at a different seed | of |")
        A("|---|---:|---:|")
        for sc, c in v["checks"]["unpaired_noise_floor_seed_diff"].items():
            A("| `%s` | %d | %d |" % (sc, c["n_vis"], c["pixel_count"]))
        A("")
        A("This is why the oracle only compares same-seed renders.  It also means")
        A("the method cannot be used to compare two renderers that cannot share a")
        A("sample stream.")
        A("")
        A("The `tree == brute` check is load-bearing: the tree build permutes the")
        A("primitive array, and overlapping boxes can be hit at exactly the same")
        A("`t`.  The shim resolves such ties by lower primitive id, so tree-shape")
        A("changes are provably invisible instead of randomly visible.")
    A("")
    if s:
        A("### Sensitivity floor")
        A("")
        A("`tools/sensitivity.py` scales the Lambert `1/pi` factor by a relative error")
        A("and finds the smallest error that the 8-bit comparison can see.")
        A("")
        A("| relative error in Lambert denominator | smallest visible-pixel count | visible in every scene |")
        A("|---|---:|---|")
        for row in s["rows"]:
            A("| %.2f%% | %s | %s |" % (100.0 * row["rel_error"], row["min_vis"],
                                         row["all_scenes_visible"]))
        A("")
        A("Smallest error visible in at least one scene: **%s**; in every scene:" %
          ("%.2f%%" % (100 * s["smallest_visible_any_scene"])
           if s["smallest_visible_any_scene"] is not None else "-"))
        A("**%s**." % ("%.2f%%" % (100 * s["smallest_visible_in_every_scene"])
                      if s["smallest_visible_in_every_scene"] is not None else "-"))
        A("")
        A("So the capture rate above is conditional on error size: photometric")
        A("defects smaller than roughly 2% of the affected term are not observable")
        A("in these scenes at this exposure.  The surviving mutant")
        A("`mat-lambert-slightly-detuned` sits at %.1f%%." %
          (100.0 / 3.16 * (3.16 - 3.14159265)))
    A("")
    A("## 6. Threats to validity")
    A("")
    A("- **Single renderer, five scenes.**  A defect that only shows at a different")
    A("  camera, a different light, or higher bounce depth would be missed.  An")
    A("  ablation run limited to `grid,rough,occlude` still caught every visible")
    A("  defect at the final settings, so the last two scenes are not load-bearing")
    A("  for this catalogue; they add margin (see detection margins above) and")
    A("  coverage of cases this catalogue happens not to contain.")
    A("- **Paired-only comparison.**  Bitwise-stable rendering is a property of")
    A("  this build and these sources; it was verified (section 5), not assumed.")
    A("- **Equivalent mutants are hand-classified** (section 4 lists the argument")
    A("  for each).  A wrong classification would corrupt the false-positive rate.")
    A("- **Sub-threshold defects are expected misses**, quantified in section 5.")
    A("  They are excluded from the headline rate.")
    A("")
    A("## 7. Reproduce everything")
    A("")
    A("```sh")
    A("cd mut")
    A("python3 -I tools/mutate.py --check            # every patch anchor matches once")
    A("python3 -I tools/validate.py                  # oracle sanity, writes results/validate.json")
    A("python3 -I tools/run_mutations.py --out results")
    A("python3 -I tools/sensitivity.py               # writes results/sensitivity.json")
    A("python3 -I tools/report.py                    # writes REPORT.md")
    A("```")
    A("")
    A("No third-party libraries: the harness is Python stdlib plus `gcc`; images are")
    A("written as raw RGB with a Python `zlib` PNG encoder.")
    A("")

    out = os.path.join(ROOT, "REPORT.md")
    open(out, "w", encoding="utf-8").write("\n".join(L))
    print("wrote", out)
    return 0


if __name__ == "__main__":
    sys.exit(main())
